"""LaTeX tables for latency, SAM 3 and the validation-selection bias, from ext/results_final and the server results.

  python ext/analysis/final_tables.py [--server DIR]   # DIR holds the server's ext/results (latency_ext.csv, sam3_*)
"""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FINAL = ROOT / "ext" / "results_final"
LATENCY = {"single": "One model", "single_tta": "One model + TTA", "e1": "Ensemble of the four variants",
           "e1_tta": "Ensemble of the four variants + TTA", "c4": "Ensemble of four baseline models",
           "c4_tta": "Ensemble of four baseline models + TTA"}
SAM3 = {"sam3_boxfill": "Filled ground-truth boxes (no SAM)", "sam3_gt_boxes": "SAM 3, ground-truth box prompts",
        "sam3_text": "SAM 3, text prompts (corrosion, rust)"}
NAMES = {"x0_baseline": "Baseline", "x1_recipe": "Small-data recipe", "x2_multi": "9 classes + unused images", "x3_seg": "Segmentation head",
         "x4_seg_cp": "Segmentation + copy-paste", "x6_multi_seg": "9 classes as polygons + unused images",
         "e1_ensemble": "Ensemble of the four variants", "c4_baselines": "Ensemble of four baseline models"}


def rows(path: Path) -> list[dict]:
    return list(csv.DictReader(open(path, encoding="utf-8")))


def latency(server: Path) -> str:
    data = {(r["strategy"], r["precision"]): r for r in rows(server / "latency_ext.csv")}
    summary = {(r["model"], r["strategy"]): float(r["map50_mean"]) for r in rows(FINAL / "summary.csv")}
    acc = {"single": ("x2_multi", "standard"), "single_tta": ("x2_multi", "tta"), "e1": ("e1_ensemble", "standard"),
           "e1_tta": ("e1_ensemble", "tta"), "c4": ("c4_baselines", "standard"), "c4_tta": ("c4_baselines", "tta")}
    out = ["% generated by ext/analysis/final_tables.py; RTX 4090, FP32, batch 1, fold r0/f0, 165 timed images",
           "\\begin{tabular}{lcccc}", "\\toprule",
           "Inference recipe & Forward passes & Latency (ms, mean / p95) & Images/s & Out-of-fold mAP@50 \\\\", "\\midrule"]
    for key, label in LATENCY.items():
        r = data[(key, "fp32")]
        out.append(f"{label} & {r['forward_passes_per_image']} & {float(r['ms_mean']):.1f} / {float(r['ms_p95']):.1f} & "
                   f"{float(r['img_per_s']):.1f} & {summary[acc[key]]:.3f} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def sam3(server: Path) -> str:
    out = ["% generated by ext/analysis/final_tables.py; 21 images with corrosion polygons, 170 without",
           "\\begin{tabular}{lcccc}", "\\toprule",
           "Mask source & IoU [95\\% CI] & Share IoU $>$ 0.5 & Images found & False masks on negatives \\\\", "\\midrule"]
    for d, label in SAM3.items():
        m = {(r["subset"], r["metric"]): r for r in rows(server / d / "sam3_summary.csv")}
        iou = m[("positives", "iou_mean")]
        out.append(f"{label} & {float(iou['value']):.3f} [{float(iou['ci_lo']):.3f}, {float(iou['ci_hi']):.3f}] & "
                   f"{100 * float(m[('positives', 'share_iou_gt_0.5')]['value']):.0f}\\% & "
                   f"{100 * float(m[('positives', 'share_detected')]['value']):.0f}\\% & "
                   f"{100 * float(m[('negatives', 'false_mask_rate')]['value']):.1f}\\% \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def valbias() -> tuple[str, list[dict]]:
    summary = {(r["model"], r["strategy"]): float(r["map50_mean"]) for r in rows(FINAL / "summary.csv")}
    val = {(r["model"], r["strategy"]): float(r["val_map50_mean"]) for r in rows(FINAL / "validation.csv")}
    out = ["% generated by ext/analysis/final_tables.py; standard pass; validation = mean inner-validation mAP@50 over 15 folds",
           "\\begin{tabular}{lccc}", "\\toprule", "Model & Validation mAP@50 & Out-of-fold mAP@50 & Gap \\\\", "\\midrule"]
    recs = []
    for model, label in NAMES.items():
        if (model, "standard") not in summary or (model, "standard") not in val:
            continue
        v, t = val[(model, "standard")], summary[(model, "standard")]
        recs.append({"model": model, "val_map50": round(v, 4), "oof_map50": round(t, 4), "gap": round(v - t, 4)})
        out.append(f"{label} & {v:.3f} & {t:.3f} & {v - t:+.3f} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n", recs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", type=Path, default=ROOT.parent / "results" / "ext" / "server_results_20261009",
                    help="server-side ext/results (latency_ext.csv, sam3_*/sam3_summary.csv)")
    args = ap.parse_args()
    for name, text in (("table_latency.tex", latency(args.server)), ("table_sam3.tex", sam3(args.server))):
        (FINAL / name).write_text(text, encoding="utf-8", newline="\n")
        print(text)
    text, recs = valbias()
    (FINAL / "table_valbias.tex").write_text(text, encoding="utf-8", newline="\n")
    with open(FINAL / "valbias.csv", "w", newline="\n", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(recs[0].keys()))
        w.writeheader()
        w.writerows(recs)
    print(text)


if __name__ == "__main__":
    main()
